/* Shared broken-image fallback for project detail media — swaps a failed
   <img> for the same dashed-border placeholder used when a project has
   no media at all, instead of leaving a broken-image icon on the page. */
function handleImgError(img) {
  const wrap = document.createElement('div');
  wrap.className = 'm-main';
  wrap.innerHTML = `
    <svg viewBox="0 0 24 24" aria-hidden="true"><rect x="2" y="3" width="20" height="14" rx="2"/><path d="M8 21h8M12 17v4"/></svg>
    <span>Image unavailable</span>`;
  img.replaceWith(wrap);
}

/* ── REAL PROJECT URLS ──────────────────────────────────────────────────
   Each case study has its own page at projects/<slug>/ (generated by
   tools/build-pages.mjs), so it can be shared with its own link preview
   and indexed on its own. Those pages are copies of index.html with
   <html data-project="slug"> and a <base href="../../">, so every relative
   path in content.js still resolves from the site root.

   The old hash routes (#/project/slug) still work, so links already sent
   out don't break, and they're what a local file:// preview uses, since a
   folder URL doesn't open its index.html there. */
const PAGE_PROJECT = document.documentElement.dataset.project || null;
const ROOT_URL     = new URL('./', document.baseURI).href;
const USE_REAL_URLS = location.protocol !== 'file:';

function projectHref(slug) {
  return USE_REAL_URLS ? `projects/${encodeURIComponent(slug)}/` : `#/project/${slug}`;
}

function getRoute() {
  if (PAGE_PROJECT) return { type: 'project', slug: PAGE_PROJECT };
  const h = window.location.hash || '#';
  if (h.startsWith('#/project/')) return { type: 'project', slug: decodeURIComponent(h.replace('#/project/', '')) };
  return { type: 'home' };
}

/* True when the visitor arrived at this project page from the homepage,
   so "Back" can be a real history step (which restores their scroll
   position) instead of a fresh load of the top of the page. */
function cameFromHome() {
  try {
    const ref = new URL(document.referrer);
    const root = new URL(ROOT_URL);
    return ref.origin === root.origin &&
           ref.pathname.replace(/index\.html$/, '') === root.pathname;
  } catch { return false; }
}

function showPage(name) {
  document.querySelectorAll('.page').forEach(p => {
    p.classList.remove('on');
    p.style.display = 'none';
  });
  const pg = document.getElementById('page-' + name);
  pg.style.display = 'block';
  requestAnimationFrame(() => pg.classList.add('on'));
}

function applyRoute() {
  const r = getRoute();
  if (r.type === 'project') {
    savedScrollY = window.scrollY;
    renderProject(r.slug);
    showPage('project');
  } else {
    showPage('home');
    /* Scroll restored here (not in the back-button handler) to avoid
       a race condition with showPage's requestAnimationFrame. */
    window.scrollTo({ top: savedScrollY, behavior: 'instant' });
    closeMobileMenu();
    resetHomeMeta();
    setTimeout(() => { initScrollObserver(); initScrollSpy(); }, 50);
  }
  updateProgress();
}

/* route() adds the View Transitions cross-fade on top of applyRoute() —
   used for actual navigations (hashchange). The very first paint calls
   applyRoute() directly from INIT at the bottom of this file: there's no
   previous rendered state to transition from on first load, and wrapping
   it in startViewTransition anyway caused a visible rendering glitch. */
function route() {
  if (document.startViewTransition && !prefersReducedMotion) {
    document.startViewTransition(applyRoute);
  } else {
    applyRoute();
  }
}

window.addEventListener('hashchange', route);


