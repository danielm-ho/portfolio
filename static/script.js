/* ══════════════════════════════════════════
   ANALYTICS (GoatCounter)
   Loads only when SITE.goatcounter holds a code, so nothing is sent until
   you turn it on in content.js. GoatCounter sets no cookies and needs no
   consent banner. Project pages are real URLs, so each one shows up as its
   own page in the dashboard; old #/project/ links are reported under the
   same projects/<slug>/ path so the numbers line up. Clicks on anything
   with data-track are counted as events.
══════════════════════════════════════════ */

function analyticsPath() {
  const r = getRoute();
  if (r.type === 'project' && !PAGE_PROJECT) {
    return new URL(`projects/${encodeURIComponent(r.slug)}/`, ROOT_URL).pathname;
  }
  return null;
}

function initAnalytics() {
  const code = (typeof SITE !== 'undefined' && SITE.goatcounter || '').trim();
  if (!code || location.protocol === 'file:') return;

  /* Label the links worth counting. Contact cells and resume links are in
     the static HTML; project links are labelled in renderProject(). */
  document.querySelectorAll('a[href$="resume.pdf"]').forEach(a => { a.dataset.track ||= 'resume'; });
  document.querySelectorAll('.ct-cell[data-site-link]').forEach(a => { a.dataset.track = 'contact: ' + a.dataset.siteLink; });
  document.querySelectorAll('a[href^="mailto:"]').forEach(a => { a.dataset.track ||= 'contact: email'; });
  const copyBtn = document.getElementById('ct-copy');
  if (copyBtn) copyBtn.dataset.track = 'contact: copy email';

  window.goatcounter = { path: p => analyticsPath() || p };

  const s = document.createElement('script');
  s.async = true;
  s.src = 'https://gc.zgo.at/count.js';
  s.dataset.goatcounter = `https://${encodeURIComponent(code)}.goatcounter.com/count`;
  document.head.appendChild(s);

  /* One delegated listener covers links rendered later, too. */
  document.addEventListener('click', e => {
    const el = e.target.closest('[data-track]');
    if (!el || !window.goatcounter?.count) return;
    window.goatcounter.count({ path: el.dataset.track, title: el.dataset.track, event: true });
  });

  /* Legacy hash navigation doesn't reload the page, so count it by hand. */
  window.addEventListener('hashchange', () => {
    const path = analyticsPath();
    if (path && window.goatcounter?.count) window.goatcounter.count({ path });
  });
}


